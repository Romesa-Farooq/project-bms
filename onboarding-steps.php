<script>

    const steps = [
        "Write a Detailed Job Description",
        "Craft a Compelling Job Offer",
        "Create a Pre-Boarding Process",
        "Make a Good First Impression",
        "Establish Your Organization's Culture and Values",
        "Introduce Your New Hire to the Team",
        "Plan a Training Schedule",
        "Set Expectations Around the Role and Performance",
        "Provide Ongoing Support and Feedback",
        "Re-Board When Necessary"
    ];


    const tbody = document.querySelector("#onboardingTable tbody");


    /*
     * Generate onboarding rows
     */
    steps.forEach((name, i) => {

        const row = document.createElement("tr");

        row.innerHTML = `
            <td class="text-center fw-medium">
                ${i + 1}
            </td>

            <td>
                <span class="fw-medium">
                    ${name}
                </span>
            </td>

            <td class="text-center">
                <div class="form-check d-flex justify-content-center">
                    <input
                        class="form-check-input"
                        type="radio"
                        name="status-${i}"
                        value="applied"
                    >
                </div>
            </td>

            <td class="text-center">
                <div class="form-check d-flex justify-content-center">
                    <input
                        class="form-check-input"
                        type="radio"
                        name="status-${i}"
                        value="not-applied"
                    >
                </div>
            </td>

            <td>
                <textarea
                    class="form-control"
                    rows="1"
                    placeholder="Add a note..."
                ></textarea>
            </td>
        `;

        tbody.appendChild(row);

    });


    /*
     * Collect onboarding data
     */
    function collectData() {

        const rows = [...tbody.querySelectorAll("tr")];

        return rows.map((row, i) => {

            const applied = row.querySelector(
                'input[value="applied"]'
            ).checked;

            const notApplied = row.querySelector(
                'input[value="not-applied"]'
            ).checked;


            return {

                step: steps[i],

                status: applied
                    ? "Applied"
                    : notApplied
                        ? "Not Applied"
                        : "Unset",

                notes: row.querySelector("textarea").value

            };

        });

    }


    /*
     * Save
     */
    document.getElementById("saveBtn").addEventListener("click", () => {

        const data = collectData();

        console.log("Onboarding data:", data);


        const appliedCount = data.filter(
            item => item.status === "Applied"
        ).length;


        const notAppliedCount = data.filter(
            item => item.status === "Not Applied"
        ).length;


        const status = document.getElementById("status");


        status.innerHTML = `
            <span class="text-success">
                <i class="ri-checkbox-circle-line me-1"></i>
                Saved ${new Date().toLocaleTimeString()} —
                ${appliedCount} of ${data.length} steps applied
                ${notAppliedCount > 0
                    ? `, ${notAppliedCount} not applied`
                    : ""}
            </span>
        `;

    });


    /*
     * Reset
     */
    document.getElementById("resetBtn").addEventListener("click", () => {

        tbody
            .querySelectorAll('input[type="radio"]')
            .forEach(radio => {
                radio.checked = false;
            });


        tbody
            .querySelectorAll("textarea")
            .forEach(textarea => {
                textarea.value = "";
            });


        document.getElementById("status").textContent = "";

    });

</script>


